"""In the single runtime, a reply to the session's own command leaves out repeats.

The session read the full page a moment ago. The page ww prints in reply to
its ``complete`` or ``next --outcome`` keeps what is new and drops what the
page before already said; a page a new or resumed session reads first, a stop
for the operator, and every page in ``auto`` stay in full.
"""

from __future__ import annotations

import json
from pathlib import Path

from tests.workflow_helpers import assignment_token
from ww.instructions import Instruction
from ww.output_adapters.json_adapter import JsonOutputAdapter
from ww.output_adapters.markdown import MarkdownOutputAdapter
from ww.service import WorkflowService
from ww.storage import Storage

STEPS = """workflows:
  - name: task
    steps:
      - develop: Implement it.
      - review: Review it.
      - publish: Publish it.
"""

REPEATING = """workflows:
  - name: task
    steps:
      - name: review
        description: Review the change.
        assess:
          assess: Are there issues?
          repeat_until: negative
          positive:
            steps:
              - fix: Fix the exact findings.
      - publish: Publish it.
"""

FAILING = """handlers:
  - broken: ~
    argv: [sh, -c, "exit 3"]
workflows:
  - name: task
    steps:
      - develop: Implement it.
      - broken: ~
"""

# What only the full page says, and the reply to the session's own command
# leaves out.
REPEATS = (
    "> Generated by `ww`; authoritative for the current task state.",
    "The full task requirements are not repeated on this page",
    "### Next steps",
    "### Previous artifacts",
    "When the work is finished, run this with every `<...>` replaced.",
    "If the work cannot be done, record why instead of completing:",
)


def _started(root: Path, config: str, runtime: str = "single") -> WorkflowService:
    (root / "ww.yaml").write_text(config, encoding="utf-8")
    service = WorkflowService(Storage(root))
    service.start(
        "task",
        "TASK-1",
        agent="codex",
        workflow_runtime=runtime,
        init_artifact="Add a --verbose flag.",
        caller_role="manager",
    )
    return service


def _page(instruction: Instruction) -> str:
    return MarkdownOutputAdapter().render_instruction(instruction)


def _complete(service: WorkflowService, text: str = "Done.") -> Instruction:
    return service.complete("TASK-1", artifact=text, summary_for_next=text)


def test_the_reply_to_a_completion_keeps_what_is_new(tmp_path: Path) -> None:
    service = _started(tmp_path, STEPS)
    first = service.next("TASK-1")
    full = _page(first)
    assert "> Generated by `ww`; authoritative" in full
    assert "### Next steps" in full
    role = "act as the worker and do the work yourself, not through a subagent"

    reply = _complete(service, "Implemented the flag.")

    page = _page(reply)
    assert reply.session_continues
    assert reply.item_name == "review"
    for repeat in REPEATS:
        assert repeat not in page
    assert "> Completion recorded successfully by `ww`." in page
    assert "## Manager and worker: perform `review`" in page
    # The role line stays: it bans subagents and names the role to act in.
    assert role in page
    assert "> Implemented the flag." in page
    assert "### Work instruction\n\nReview it." in page
    assert '--summary="<one or two sentences for the next step>"' in page


def test_a_page_read_first_stays_in_full(tmp_path: Path) -> None:
    service = _started(tmp_path, STEPS)
    service.next("TASK-1")
    _complete(service)

    for again in (service.instruction("TASK-1"), service.next("TASK-1")):
        page = _page(again)
        assert not again.session_continues
        for repeat in REPEATS:
            assert repeat in page


def test_the_reply_to_an_outcome_continues_the_session(tmp_path: Path) -> None:
    service = _started(tmp_path, REPEATING)
    service.next("TASK-1")
    choose = _complete(service, "Found one issue.")
    assert choose.session_continues
    assert "### Choose the outcome" in _page(choose)

    fix = service.next("TASK-1", outcome="positive", caller_role="manager")

    page = _page(fix)
    assert fix.session_continues
    assert fix.item_name == "fix"
    assert (
        "Repeating assessment, round 1: it repeats until the outcome is `negative`."
        in page
    )
    assert "```json" not in page
    resumed = _page(service.instruction("TASK-1"))
    assert "Repeating assessment\n" in resumed
    assert "```json" in resumed


def test_a_stop_for_the_operator_is_shown_in_full(tmp_path: Path) -> None:
    service = _started(tmp_path, FAILING)
    service.next("TASK-1")

    stop = _complete(service)

    assert stop.operator_reason is not None
    assert "> Generated by `ww`; authoritative" in _page(stop)


def test_the_auto_runtime_is_unchanged(tmp_path: Path) -> None:
    service = _started(tmp_path, STEPS, "auto")
    service.next("TASK-1", caller_role="manager")

    reply = service.complete(
        "TASK-1",
        artifact="Done.",
        summary_for_next="Done.",
        caller_role="worker",
        assignment=assignment_token(service, "TASK-1"),
    )

    assert not reply.session_continues
    assert "> Generated by `ww`; authoritative" in _page(reply)


def test_the_json_page_keeps_every_field(tmp_path: Path) -> None:
    service = _started(tmp_path, STEPS)
    service.next("TASK-1")

    data = json.loads(JsonOutputAdapter().render_instruction(_complete(service)))

    assert data["session_continues"] is True
    assert data["next_steps"] == ["publish"]
    assert data["requirements_command"]
