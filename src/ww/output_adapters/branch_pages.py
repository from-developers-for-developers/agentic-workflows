"""Markdown for one branch of a parallel step: its page and its recording.

A branch's worker reads a page of its own, shorter than a step's: the
branch's prompt, the task, and the one command that records its artifact.
It never completes the step; the step's performer does, once every branch
has recorded its artifact.
"""

from __future__ import annotations

import shlex

from ww.instructions.models import BranchPage, BranchRecorded
from ww.instructions.text import READONLY
from ww.output_adapters.markdown import (
    Lines,
    _append_section,
    _document,
    requested_setting_lines,
)


def render_branch_page(page: BranchPage) -> str:
    """The page of branch ``page.branch`` for the subagent that runs it."""
    branch = page.branch
    codename = f" ({page.task_codename})" if page.task_codename else ""
    lines: Lines = [
        f"# {page.task_id}{codename} · {page.workflow}",
        "",
        "> Generated by `ww`; authoritative for the current task state.",
        "",
        f"## Worker: perform the `{branch.name}` branch of `{page.step}`",
        "",
        f"You are a worker running one branch of the parallel step `{page.step}`."
        + (
            " The other branches, "
            + ", ".join(f"`{name}`" for name in page.siblings)
            + ", run at the same time in other sessions: do only this branch's "
            "work, and leave their subjects to them."
            if page.siblings
            else ""
        )
        + " Do not complete the step and do not run `next`: record this "
        "branch's artifact with the command below, then report back to the "
        "session that launched you.",
    ]
    if page.readonly:
        lines.extend(["", f"> **Readonly.** {READONLY}"])
    if page.working_directory:
        _append_section(lines, "Working directory")
        lines.extend(
            [
                "Before doing any task work, switch to this task workspace and "
                "keep it as your current directory:",
                "",
                "```console",
                f"cd {shlex.quote(page.working_directory)}",
                "```",
            ]
        )
    settings = requested_setting_lines(
        branch.requested_model, branch.requested_reasoning
    )
    if settings:
        _append_section(lines, "Requested worker")
        lines.extend(settings)
    if branch.profile_instruction:
        _append_section(lines, "Profile")
        lines.append(branch.profile_instruction)
    if page.task_requirements:
        _append_section(lines, "Task requirements")
        lines.append(page.task_requirements)
    if page.task_amendments:
        _append_section(lines, "Requirement amendments")
        lines.extend(
            f"- {entry.at} ({entry.role}): {entry.text}"
            for entry in page.task_amendments
        )
    _append_section(lines, "Work instruction")
    lines.append(page.action_text)
    if page.artifacts_command:
        lines.extend(
            [
                "",
                "Earlier steps' artifacts, listed as JSON with absolute paths: "
                f"`{page.artifacts_command}`",
            ]
        )
    if page.modes:
        _append_section(lines, "Modes")
        lines.extend(["Work in these modes throughout this branch:", ""])
        for mode in page.modes:
            guidance = " ".join(mode.description)
            lines.append(f"- `{mode.name}`" + (f" — {guidance}" if guidance else ""))
    _append_section(lines, "Branch completion command")
    if branch.artifact:
        lines.extend(
            [
                f"This branch's artifact is already recorded at `{branch.artifact}`; "
                "running the command again replaces it.",
                "",
            ]
        )
    lines.extend(
        [
            "When the work is finished, record the whole result, with "
            "`<...>` replaced:",
            "",
            "```console",
            page.completion_command,
            "```",
            "",
            "Then report back in a sentence or two and stop.",
        ]
    )
    return _document(lines)


def render_branch_recorded(result: BranchRecorded) -> str:
    """What ``complete --branch`` recorded, and what the step still waits for."""
    lines: Lines = [
        f"Recorded the artifact of branch `{result.branch}` of `{result.step}` "
        f"at `{result.artifact}`.",
        "",
    ]
    if result.missing:
        lines.append(
            "Still waiting for: "
            + ", ".join(f"`{name}`" for name in result.missing)
            + "."
        )
    else:
        lines.append(
            f"Every branch of `{result.step}` has recorded its artifact; the "
            "session that launched the branches completes the step."
        )
    lines.extend(
        [
            "",
            "Report back to that session in a sentence or two and stop: this "
            "branch's work is done.",
        ]
    )
    return _document(lines)
